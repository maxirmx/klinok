export type DiagnosisTaxonomyId = `diagnosis.${string}`;

export interface DiagnosisChoice {
  selectedId?: DiagnosisTaxonomyId;
  customText: string;
}

export interface DiagnosisDifferential {
  selectedIds: readonly DiagnosisTaxonomyId[];
  customTexts: readonly string[];
}

export interface LegacyDiagnosisDifferential {
  selectedIds: readonly DiagnosisTaxonomyId[];
  customText: string;
}

export interface DiagnosisSectionValue {
  preliminary: DiagnosisChoice;
  differential: DiagnosisDifferential | LegacyDiagnosisDifferential;
  confirmed: DiagnosisChoice;
}

export interface DiagnosisCatalogOption {
  id: DiagnosisTaxonomyId;
  label: string;
}

export interface DiagnosisCatalogGroup {
  id: string;
  label: string;
  options?: readonly DiagnosisCatalogOption[];
  groups?: readonly DiagnosisCatalogGroup[];
}

export const DIAGNOSIS_TOP_LEVEL_OPTIONS: readonly DiagnosisCatalogOption[] = [
  { id: "diagnosis.general.019", label: "Клинически здорово" },
];

function options(prefix: string, labels: readonly string[]): DiagnosisCatalogOption[] {
  return labels.map((label, index) => ({
    id: `${prefix}.${String(index + 1).padStart(3, "0")}` as DiagnosisTaxonomyId,
    label,
  }));
}

